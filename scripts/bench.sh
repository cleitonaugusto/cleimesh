#!/usr/bin/env bash
# Reproducible benchmarks (R11). Runs the criterion
# benches of the enforcement path and writes docs/benchmarks.md with the
# machine, versions and commit they ran on.
#
#   scripts/bench.sh            # all benches + Docker reference if available
#   NO_DOCKER=1 scripts/bench.sh
#   REPORT_ONLY=1 scripts/bench.sh   # rewrite the report from the last run
#
# The bench profile skips full LTO (CARGO_PROFILE_BENCH_LTO=false,
# 16 codegen units): full LTO on wasmtime needs more memory than a typical
# dev machine has free. Numbers are therefore slightly pessimistic against
# the shipped release profile.
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."

export CARGO_PROFILE_BENCH_LTO=false
export CARGO_PROFILE_BENCH_CODEGEN_UNITS=16
JOBS="${JOBS:-1}"
TARGET_DIR="$(cargo metadata --format-version 1 --no-deps | python3 -c 'import json,sys; print(json.load(sys.stdin)["target_directory"])')"

if [ -z "${REPORT_ONLY:-}" ]; then
  cargo bench -j "$JOBS" -p cleimesh-aat --bench verify -- --noplot
  cargo bench -j "$JOBS" -p cleimesh-receipt --bench append -- --noplot
  cargo bench -j "$JOBS" -p cleimesh-p2p --bench enforcement -- --noplot
fi

DOCKER_MS=""
if [ -z "${NO_DOCKER:-}" ] && command -v docker >/dev/null && docker info >/dev/null 2>&1; then
  docker pull -q alpine:3.20 >/dev/null
  runs=10 total=0
  for _ in $(seq $runs); do
    start=$(date +%s%N)
    docker run --rm --network none alpine:3.20 echo oi >/dev/null
    total=$(( total + $(date +%s%N) - start ))
  done
  DOCKER_MS=$(python3 -c "print(round($total / $runs / 1e6, 1))")
fi

python3 - "$TARGET_DIR/criterion" "$DOCKER_MS" <<'PY'
import json, os, platform, subprocess, sys
root, docker_ms = sys.argv[1], sys.argv[2]

def run(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "?"

def estimate(path):
    with open(os.path.join(root, path, "new", "estimates.json")) as f:
        e = json.load(f)
    return e["median"]["point_estimate"], e["median"]["confidence_interval"]

def fmt(ns):
    if ns >= 1e6: return f"{ns/1e6:.2f} ms"
    if ns >= 1e3: return f"{ns/1e3:.1f} µs"
    return f"{ns:.0f} ns"

rows = []
for length in (1, 3, 8, 16):
    rows.append((f"Verify an AAT chain of {length} token(s), with proof of possession", f"aat_verify/chain_length/{length}"))
rows += [
    ("Sign and chain a receipt (no disk)", "receipt/sign_and_chain"),
    ("Append a receipt with fsync", "receipt/append_with_fsync"),
    ("Verify a 1000-receipt log", "receipt/verify_log_1000_lines"),
    ("`echo` straight in the sandbox (baseline)", "echo_call/sandbox_only"),
    ("`echo` through `run_local`: AAT chain of 2 + sandbox grants + 2 receipts with fsync", "echo_call/run_local_aat_receipts"),
]
cpu = run("sh", "-c", "lscpu | sed -n 's/^Model name: *//p'") or platform.processor()
ram = run("sh", "-c", "free -h | awk '/Mem:/{print $2}'")
lines = [
    "# Benchmarks",
    "",
    "Generated by `scripts/bench.sh` (R11). Medians from criterion, 95% confidence interval in brackets.",
    "",
    f"- Commit: `{run('git', 'rev-parse', '--short', 'HEAD')}`{' (dirty tree)' if run('git', 'status', '--porcelain') else ''}",
    f"- Machine: {cpu}, {os.cpu_count()} threads, {ram} RAM, {platform.system()} {platform.release()}",
    f"- Toolchain: {run('rustc', '--version')}",
    "- Profile: bench (release without full LTO, 16 codegen units)",
    "- Conditions: a desktop in normal use (browser, IDE open); expect run-to-run noise, most of all in the Docker reference.",
    "",
    "| What | Median |",
    "|---|---|",
]
medians = {}
for label, path in rows:
    try:
        m, ci = estimate(path)
        medians[path] = m
        lines.append(f"| {label} | {fmt(m)} [{fmt(ci['lower_bound'])} – {fmt(ci['upper_bound'])}] |")
    except FileNotFoundError:
        lines.append(f"| {label} | not run |")
base, full = medians.get("echo_call/sandbox_only"), medians.get("echo_call/run_local_aat_receipts")
lines.append("")
if base and full:
    lines.append(f"Enforcement overhead per call (run_local − sandbox only): **{fmt(full - base)}**.")
    lines.append("")
lines.append("Modules are compiled and linked once, cached by the SHA-256 of their bytes (R4): the `echo` rows measure instantiating the module and running the call.")
lines.append("")
if docker_ms:
    lines.append(f"Reference: `docker run --rm --network none alpine:3.20 echo oi`, mean of 10 runs: **{docker_ms} ms** (one container per call, image already pulled).")
else:
    lines.append("Reference: Docker not measured on this run.")
lines.append("")
lines.append("Not measured yet: Wassette on the same machine (not installed), binary size and startup (R10).")
with open("docs/benchmarks.md", "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
PY
